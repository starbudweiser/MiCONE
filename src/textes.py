DEFAUT = "en"   # toute langue non prise en charge bascule sur l'anglais


def _langue_systeme() -> str:
    """Première langue préférée de macOS prise en charge par l'appli, sinon l'anglais."""
    force = os.environ.get("MICONE_LANG", "")[:2].lower()
    if force in TEXTES:
        return force
    candidats = []
    try:
        from PyQt6.QtCore import QLocale
        candidats += QLocale.system().uiLanguages()
    except Exception:
        pass
    candidats.append(locale.getlocale()[0] or "")
    return choisir(candidats)


def choisir(candidats: list[str]) -> str:
    """La langue préférée décide : prise en charge, elle est retenue ; sinon, l'anglais."""
    for c in candidats:
        if c:
            code = c.replace("_", "-").split("-")[0].lower()
            return code if code in TEXTES else DEFAUT
    return DEFAUT


LANGUE = _langue_systeme()


def t(cle: str, **kw) -> str:
    texte = TEXTES[LANGUE].get(cle) or TEXTES[DEFAUT].get(cle, cle)
    return (texte.format(**kw) if kw else texte).strip()
